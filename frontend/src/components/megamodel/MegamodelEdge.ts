/**
 * MegamodelEdge — Types and Manhattan edge routing for the Megamodel diagram.
 *
 * Edges are orthogonal polylines with rounded corners (quadratic bezier, r=4).
 * Anchor points are spread when multiple edges share the same side of a node.
 */

// ─── Constants ────────────────────────────────────────────────────────────────

export const NODE_W = 220;
export const NODE_H = 130;
const CORNER_R = 4;

// ─── Types ────────────────────────────────────────────────────────────────────

export type Side = 'top' | 'bottom' | 'left' | 'right';

export interface Point {
    x: number;
    y: number;
}

export type MmNodeKind = 'metamodel' | 'model' | 'transformation' | 'viewpoint';

export interface MmNodeStats {
    classCount?: number;
    referenceCount?: number;
    attributeCount?: number;
    objectCount?: number;
    linkCount?: number;
    ruleCount?: number;
    mappingCount?: number;
    completionPercent?: number;
}

export interface MmNodeStatus {
    type: 'valid' | 'warning' | 'info';
    label: string;
}

export interface MmNode {
    id: string;
    kind: MmNodeKind;
    name: string;
    badgeLabel: string;
    typeLabel: string;
    x: number;
    y: number;
    stats: MmNodeStats;
    status: MmNodeStatus;
    /** True if this model was generated by a transformation */
    generated?: boolean;
    /** Human-readable generation info (e.g. "2m ago by MyTransform") */
    generatedLabel?: string;
}

export type MmEdgeType = 'conformsTo' | 'uses' | 'inputOf' | 'outputOf' | 'definedOn' | 'renderedBy' | 'generatedBy' | 'sourceOf' | 'instanceInputOf';

export interface MmEdgeStyle {
    color: string;
    dasharray?: string;
    strokeWidth: number;
    opacity?: number;
}

export interface MmEdge {
    id: string;
    from: string;
    to: string;
    type: MmEdgeType;
    label: string;
    style: MmEdgeStyle;
    fromSide: Side;
    toSide: Side;
    /** Tooltip of the label pill, when the pill does not say it all */
    title?: string;
}

