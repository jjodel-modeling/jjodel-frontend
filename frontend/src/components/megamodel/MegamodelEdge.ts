/** The text of an edge's pill: the label of its kind, or `included` for the input of an included model (R-JTG-35). */
export function edgeLabelOf(type: MmEdgeType, metadata?: Record<string, unknown>): string {
    return metadata?.included ? 'included' : EDGE_STYLES[type].label;
}

/** The tooltip of an edge's pill: the full text of an included input, nothing for the others. */
export function edgeTitleOf(type: MmEdgeType, metadata?: Record<string, unknown>): string | undefined {
    return metadata?.included ? `${EDGE_STYLES[type].label} (included)` : undefined;
}

// ─── Port / anchor helpers ────────────────────────────────────────────────────

export function getPort(node: MmNode, side: Side, t = 0.5): Point {
    switch (side) {
        case 'top':    return { x: node.x + NODE_W * t,  y: node.y };
        case 'bottom': return { x: node.x + NODE_W * t,  y: node.y + NODE_H };
        case 'left':   return { x: node.x,               y: node.y + NODE_H * t };
        case 'right':  return { x: node.x + NODE_W,      y: node.y + NODE_H * t };
    }
}

/**
 * Compute spread `t` values for N edges sharing the same side of a node.
 * Returns an array of length N, each value in (0, 1).
 */
export function spreadAnchors(count: number): number[] {
    const result: number[] = [];
    for (let k = 1; k <= count; k++) {
        result.push(k / (count + 1));
    }
    return result;
}

/**
 * Geometry-aware anchor side selection.
 *
 * Picks the side of each node that faces the other, based on the dominant axis
 * of separation between node centers (horizontal gap dominates → left/right,
 * vertical → top/bottom). This replaces the static per-edge-type sides from
 * `edgeSides()` so an edge always exits/enters on the side actually facing its
 * counterpart — including after the user drags nodes around the canvas.
 *
 * `fallbackFrom` / `fallbackTo` are the static per-type sides; they are returned
 * only for the degenerate case of perfectly overlapping node centers.
 *
 * FUTURE ENHANCEMENT (anchor handling, level 3): allow the user to manually
 * grab an edge endpoint and pin it to a chosen side + offset, overriding this
 * automatic choice. Since megamodel edges are derived (never persisted on the
 * edge itself), such overrides would be stored per stable edge id in
 * localStorage, mirroring the node-position persistence (`savePositions`).
 * This function would then be the auto fallback when no manual override exists.
 */
export function computeAdaptiveSides(
    from: MmNode,
    to: MmNode,
    fallbackFrom: Side,
    fallbackTo: Side,
): { fromSide: Side; toSide: Side } {
    const dx = (to.x + NODE_W / 2) - (from.x + NODE_W / 2);
    const dy = (to.y + NODE_H / 2) - (from.y + NODE_H / 2);

    // Overlapping centers — no meaningful direction, keep the semantic default.
    if (dx === 0 && dy === 0) return { fromSide: fallbackFrom, toSide: fallbackTo };

    if (Math.abs(dx) >= Math.abs(dy)) {
        return dx >= 0
            ? { fromSide: 'right', toSide: 'left' }
            : { fromSide: 'left', toSide: 'right' };
    }
    return dy >= 0
        ? { fromSide: 'bottom', toSide: 'top' }
        : { fromSide: 'top', toSide: 'bottom' };
}

// ─── Manhattan routing ────────────────────────────────────────────────────────

/** Distance between two vertical tracks in one gap (the base grid). */
export const TRACK_GAP = 8;

export interface RouteEnds {
    p1: Point;
    exitSide: Side;
    p2: Point;
    entrySide: Side;
}

const isVerticalSide = (side: Side): boolean => side === 'top' || side === 'bottom';

/** The y of a route's left end and of its right end. */
function leftRightY(r: RouteEnds): { a: number; b: number } {
    return r.p1.x <= r.p2.x ? { a: r.p1.y, b: r.p2.y } : { a: r.p2.y, b: r.p1.y };
}

/** How many times two routes cross when `l` takes the track on the left of `r`'s. */
function crossingsOf(l: RouteEnds, r: RouteEnds): number {
    const left = leftRightY(l);
    const right = leftRightY(r);
    const within = (y: number, e: { a: number; b: number }) =>
        Math.min(e.a, e.b) < y && y < Math.max(e.a, e.b);
    return (within(right.a, left) ? 1 : 0) + (within(left.b, right) ? 1 : 0);
}

/**
 * The offset of each route's vertical segment from the centre of its gap. Routes whose vertical
 * segments fall on one x get a track each, TRACK_GAP apart and centred there; a route alone in
 * its gap gets 0. Routes that leave and enter a node horizontally are the only ones with such a
 * segment. The order starts from the height of the left end, and neighbours swap while that
 * removes crossings: a crossing depends only on which of the two is on the left.
 */
export function verticalTrackOffsets(routes: RouteEnds[]): number[] {
    const offsets: number[] = routes.map(() => 0);

    const gaps = new Map<number, number[]>();
    routes.forEach((r, i) => {
        if (isVerticalSide(r.exitSide) || isVerticalSide(r.entrySide)) return;
        const key = Math.round((r.p1.x + r.p2.x) / 2);
        if (!gaps.has(key)) gaps.set(key, []);
        gaps.get(key)!.push(i);
    });

    for (const indices of gaps.values()) {
        const order = [...indices].sort((i, j) =>
            leftRightY(routes[i]).a - leftRightY(routes[j]).a || leftRightY(routes[i]).b - leftRightY(routes[j]).b);

        for (let swapped = true; swapped;) {
            swapped = false;
            for (let k = 0; k + 1 < order.length; k++) {
                const [l, r] = [routes[order[k]], routes[order[k + 1]]];
                if (crossingsOf(r, l) < crossingsOf(l, r)) {
                    [order[k], order[k + 1]] = [order[k + 1], order[k]];
                    swapped = true;
                }
            }
        }

        order.forEach((routeIndex, position) => {
            offsets[routeIndex] = (position - (order.length - 1) / 2) * TRACK_GAP;
        });
    }

    return offsets;
}

/**
 * Compute waypoints for a Manhattan (orthogonal) route between two ports.
 * Always exits/enters perpendicular to the port side.
 * `trackOffset` shifts a vertical segment that runs between two horizontal ports.
 */
export function routePoints(p1: Point, exitSide: Side, p2: Point, entrySide: Side, trackOffset = 0): Point[] {
    const exitV  = exitSide === 'top' || exitSide === 'bottom';
    const entryV = entrySide === 'top' || entrySide === 'bottom';

    if (exitV && entryV) {
        const mid = (p1.y + p2.y) / 2;
        return [p1, { x: p1.x, y: mid }, { x: p2.x, y: mid }, p2];
    }
    if (!exitV && !entryV) {
        const mid = (p1.x + p2.x) / 2 + trackOffset;
        return [p1, { x: mid, y: p1.y }, { x: mid, y: p2.y }, p2];
    }
    if (exitV && !entryV) {
        return [p1, { x: p1.x, y: p2.y }, p2];
    }
    // !exitV && entryV
    return [p1, { x: p2.x, y: p1.y }, p2];
}

// ─── SVG path with rounded corners ────────────────────────────────────────────

/**
 * Build an SVG path string from waypoints with rounded corners (r = CORNER_R).
 * Uses quadratic bezier arcs at each bend.
 */
export function buildRoundedPath(rawPts: Point[]): string {
    // Drop consecutive duplicates: a zero-length segment would divide 0/0 below.
    const pts = rawPts.filter((p, i) => i === 0 || p.x !== rawPts[i - 1].x || p.y !== rawPts[i - 1].y);
    if (pts.length < 2) return '';
    if (pts.length === 2) return `M${pts[0].x},${pts[0].y} L${pts[1].x},${pts[1].y}`;

    const r = CORNER_R;
    const parts: string[] = [`M${pts[0].x},${pts[0].y}`];

    for (let i = 1; i < pts.length - 1; i++) {
        const prev = pts[i - 1];
        const curr = pts[i];
        const next = pts[i + 1];

        // Vector from curr to prev / next
        const dxPrev = prev.x - curr.x;
        const dyPrev = prev.y - curr.y;
        const dxNext = next.x - curr.x;
        const dyNext = next.y - curr.y;

        const lenPrev = Math.sqrt(dxPrev * dxPrev + dyPrev * dyPrev);
        const lenNext = Math.sqrt(dxNext * dxNext + dyNext * dyNext);

        // Guard: a zero-length segment cannot be normalised
        if (lenPrev === 0 || lenNext === 0) continue;

        // Clamp radius so it doesn't exceed half the segment length
        const rr =Math.min(r, lenPrev / 2, lenNext / 2);

        // Points just before/after the corner
        const beforeX = curr.x + (dxPrev / lenPrev) * rr;
        const beforeY = curr.y + (dyPrev / lenPrev) * rr;
        const afterX  = curr.x + (dxNext / lenNext) * rr;
        const afterY  = curr.y + (dyNext / lenNext) * rr;

        parts.push(`L${beforeX},${beforeY}`);
        parts.push(`Q${curr.x},${curr.y} ${afterX},${afterY}`);
    }

    const last = pts[pts.length - 1];
    parts.push(`L${last.x},${last.y}`);

    return parts.join(' ');
}

// ─── Label positioning ────────────────────────────────────────────────────────

/**
 * Find the midpoint of the longest segment in a polyline — used for label placement.
 */
export function labelMidpoint(pts: Point[]): Point {
    if (pts.length < 2) return pts[0] ?? { x: 0, y: 0 };

    let bestLen = 0;
    let bestMid: Point = { x: (pts[0].x + pts[1].x) / 2, y: (pts[0].y + pts[1].y) / 2 };

    for (let i = 0; i < pts.length - 1; i++) {
        const dx = pts[i + 1].x - pts[i].x;
        const dy = pts[i + 1].y - pts[i].y;
        const len = Math.abs(dx) + Math.abs(dy); // Manhattan length
        if (len > bestLen) {
            bestLen = len;
            bestMid = { x: (pts[i].x + pts[i + 1].x) / 2, y: (pts[i].y + pts[i + 1].y) / 2 };
        }
    }
    return bestMid;
}
