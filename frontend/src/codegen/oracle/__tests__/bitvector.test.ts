/**
 * Bit-vectors through the runner and the oracle (R-BV, slice S3, P-2026-10-21-0640; R-GEN-8, R-GEN-11).
 *
 * The runner: a worker whose two sides talk over a real `MessageChannel`, so the request and the reply are each a
 * structured clone, as between a browser worker and the main thread; the worker side is the worker's own
 * `bootWorker`. A vector goes in as an argument and comes back as a result: a clone keeps the own keys of a
 * `$BitVector` and loses its prototype, and both sides still read it as a vector.
 *
 * The oracle: the turnstile (codegen/examples/) with an 8-bit register `r` on `locked`, incremented by `tc` and read
 * by the guard of `ts`. The scenario fires `tc` 258 times, so the register wraps at 256 and `ts` fires at 2; the
 * program generated by the example's templates passes the oracle at every step, and the same program with its
 * increment mutated diverges at the first `coin`. Each test name says which break kills it; the bench is in the
 * commit body.
 */

import { describe, it, expect } from 'vitest';
import { isBitVector } from '../../../jjel/evaluator/context';
import { toVerilog } from '../../../jjel/evaluator/builtins/bitvectors';
import type { ScenarioRecord } from '../../../model/simulation/scenarioCodec';
import { generate } from '../../engine/generate';
import { readModelTemplates } from '../../engine/templateCodec';
import { runInWorker } from '../../runner/runner';
import type { RunnerErrorEvent, RunnerWorker } from '../../runner/runner';
import { bootWorker } from '../../runner/runner.worker';
import type { ModuleLoader, WorkerScope } from '../../runner/runner.worker';
import { JS_RUNTIME } from '../../target/js/printer';
import { runOracle } from '../oracle';
import { inProcess, loadExample, recordOf } from './exampleFixture';

// ── the runner over a MessageChannel ─────────────────────────────────────────

let loads = 0;

/** The in-process loader of runner.test.ts: the code as a real ES module from a fresh `data:` URL. */
const dataLoader: ModuleLoader = code => {
    const url = 'data:text/javascript;base64,' + Buffer.from(`${code}\n// load ${++loads}\n`).toString('base64');
    return { url, module: import(/* @vite-ignore */ url) };
};

/** A worker as two ports of a `MessageChannel`: every message, either way, is a structured clone. */
class ChannelWorker implements RunnerWorker {
    onmessage: ((ev: { data: unknown }) => void) | null = null;
    onerror: ((ev: RunnerErrorEvent) => void) | null = null;
    private readonly channel = new MessageChannel();
    constructor() {
        const inside = this.channel.port2;
        const scope: WorkerScope = { postMessage: (m: unknown) => inside.postMessage(m), onmessage: null };
        inside.onmessage = ev => scope.onmessage?.(ev);
        this.channel.port1.onmessage = ev => this.onmessage?.({ data: ev.data });
        bootWorker(scope, dataLoader);
    }
    postMessage(message: unknown): void {
        this.channel.port1.postMessage(message);
    }
    terminate(): void {
        this.channel.port1.close();
        this.channel.port2.close();
    }
}

/** The printer's runtime as a module, with one export that adds 1 to an 8-bit vector. */
const MODULE = `${JS_RUNTIME}\nexport function inc(x) { return $add(x, $bv(8, false, 0x1n)); }\n`;

describe('the runner: a bit-vector across the worker boundary', () => {
    it('a vector argument is cloned in, the result is cloned out as a vector, and fed back in (mutant: $isBV reads the $BitVector class)', async () => {
        const v254 = { __type: 'BitVector', width: 8, signed: false, bits: 0xfen };
        const first = await runInWorker({ code: MODULE, calls: [{ fn: 'inc', args: [v254] }] }, () => new ChannelWorker());
        expect(first.ok, JSON.stringify(first, (_k, x) => (typeof x === 'bigint' ? `${x}n` : x))).toBe(true);
        const out = (first as unknown as { results: unknown[] }).results[0];
        expect(isBitVector(out)).toBe(true);
        expect(out).toEqual({ __type: 'BitVector', width: 8, signed: false, bits: 0xffn });
        expect(toVerilog(out as never)).toBe("8'hff");
        // The clone that came out goes back in: the wrap at 256 happens on the other side.
        const second = await runInWorker({ code: MODULE, calls: [{ fn: 'inc', args: [out] }] }, () => new ChannelWorker());
        expect(second.ok).toBe(true);
        const back = (second as unknown as { results: unknown[] }).results[0];
        expect(isBitVector(back)).toBe(true);
        expect(toVerilog(back as never)).toBe("8'h00");
    });

    it('a width mismatch inside the worker is a runtime error, not a value (mutant: $add on vectors falls back to number addition)', async () => {
        const v4 = { __type: 'BitVector', width: 4, signed: false, bits: 1n };
        const r = await runInWorker({ code: MODULE, calls: [{ fn: 'inc', args: [v4] }] }, () => new ChannelWorker());
        expect(r.ok).toBe(false);
        expect((r as { error: { kind: string } }).error.kind).toBe('runtime');
    });
});

// ── the oracle: an 8-bit counter on the turnstile ────────────────────────────

const COINS = 258;

/**
 * The turnstile with the register `r` on every `Initial`, that is on `locked` (domain null: the templates' domain
 * check has no word case). Declared on the metamodel: a model declares globals only (stateAttributesCodec.ts).
 */
function counter() {
    const ex = loadExample('turnstile');
    const MM = ex.lookup[ex.metamodelId];
    const declared = MM._state.simStateAttributes ? JSON.parse(MM._state.simStateAttributes) : { v: 1, attrs: [] };
    declared.attrs.push({ name: 'r', metaclass: 'C_Initial', space: 'semantic', domain: null, initial: 'bits(8, 0)' });
    MM._state.simStateAttributes = JSON.stringify(declared);
    const value = (owner: string, feature: string) =>
        Object.values(ex.lookup).find((d: any) => d.className === 'DValue' && d.father === owner && d.instanceof === feature) as any;
    value('tc', 'F_Transition_effect').values = ['locked.[r] := locked.[r] + bits(8, 1)'];
    value('ts', 'F_Transition_guard').values = ['locked.[r] == bits(8, 2)'];
    const scenario: ScenarioRecord = {
        ...ex.scenario,
        name: 'Count past 256, stop at 2',
        steps: [
            { event: 'push', selector: null, kind: 'discard' },
            ...Array.from({ length: COINS }, () => ({ event: 'coin', selector: 'tc', kind: 'fired' as const })),
            { event: 'stop', selector: 'ts', kind: 'fired' },
        ],
        expect: 'locked.[r] == bits(8, 2)',
    };
    const out = generate(recordOf(ex.lookup, ex.modelId), ex.lookup, ex.modelId, readModelTemplates(ex.lookup, ex.modelId).templates, 'main');
    const oracle = (code: string) =>
        runOracle({ lookup: ex.lookup, modelId: ex.modelId, globals: recordOf(ex.lookup, ex.modelId), scenario, code, map: out.map, run: inProcess });
    return { out, scenario, oracle };
}

/** The printed increment: the one `0x1n` of the program. */
const INCREMENT = '$bv(8, false, 0x1n)';

describe('the oracle: an 8-bit register that wraps at 256', () => {
    it('generates the register as a vector, with no error', () => {
        const { out } = counter();
        expect(out.errors).toEqual([]);
        expect(out.code.split(INCREMENT).length - 1).toBe(1);
        expect(out.code).toContain('$bv(8, false, 0x2n)');
    });

    it(`passes the oracle over ${COINS} increments and the stop at 2 (mutant: the prelude's + without asUintN, the register not wrapping)`, async () => {
        const { scenario, oracle, out } = counter();
        const result = await oracle(out.code);
        expect(result.ok, JSON.stringify(result, (_k, x) => (typeof x === 'bigint' ? `${x}n` : x)).slice(0, 1500)).toBe(true);
        expect(result.sim.length).toBe(scenario.steps.length + 1);
        expect(result.gen.map(s => s.kind)).toEqual(['initial', ...scenario.steps.map(s => s.kind)]);
    });

    it('the increment mutated to 2 diverges on observe at the first coin, at tc', async () => {
        const { oracle, out } = counter();
        const result = await oracle(out.code.replace(INCREMENT, '$bv(8, false, 0x2n)'));
        expect(result).toMatchObject({ ok: false, step: 2, kind: 'observe', transitionId: 'tc' });
    });
});
