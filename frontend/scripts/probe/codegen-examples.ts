const PROJECTS = String.raw`JSON.parse(localStorage.getItem('projects') || '[]').map((p) => ({ id: p.id, name: p.name }))`;

/** The element ids of a stored project, read from its saved state as the app reads it. */
const STORED_IDS = (pid: string) => String.raw`(async () => {
  const j = await import('/src/joiner/index.ts');
  const p = JSON.parse(localStorage.getItem('projects') || '[]').find((x) => x.id === ${JSON.stringify(pid)});
  if (!p) return null;
  const lookup = JSON.parse(await j.U.decompressState(p.state)).idlookup;
  return Object.values(lookup).filter((d) => d && typeof d === 'object' && /^D(Model|Package|Class|Attribute|Reference|Object|Value|Graph|Vertex|Edge)$/.test(d.className))
    .map((d) => d.id).filter((id) => /^Pointer\d/.test(id));
})()`;

const LOADED = (mm: string, m1: string) => String.raw`(() => {
  try {
    const all = Object.values(window.windoww.store.getState().idlookup).filter((d) => d && typeof d === 'object');
    const a = all.find((d) => d.className === 'DModel' && d.isMetamodel && d.name === ${JSON.stringify(mm)});
    const b = all.find((d) => d.className === 'DModel' && !d.isMetamodel && d.name === ${JSON.stringify(m1)});
    if (!a || !b || document.querySelectorAll('.dock-tab').length === 0) return null;
    return { mm: a.id, m1: b.id };
  } catch (e) { return null; }
})()`;

const PANE = (m1Id: string) => `(document.querySelector('[role="tabpanel"][aria-labelledby$="-tab-${m1Id}"]'))`;
const CLICK = (expr: string) => String.raw`(() => { const el = ${expr}; if (!el) return { found: false }; el.click(); return { found: true }; })()`;
const BOX = (expr: string) => String.raw`(() => { const el = ${expr}; if (!el) return null; const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height }; })()`;

/** The run row and the result area, as the user reads them. */
const STATE = (panel: string) => String.raw`(() => {
  const p = ${panel};
  const row = p && p.querySelector('.codegen-panel__run');
  if (!row) return null;
  const select = row.querySelector('select[aria-label="Scenario"]');
  const chk = [...row.querySelectorAll('button')].find((b) => /^Check(ing)?$/.test(b.textContent.trim()));
  const pass = p.querySelector('.codegen-panel__result--pass');
  const bad = p.querySelector('.codegen-panel__result--error');
  const plain = [...p.querySelectorAll('.codegen-panel__result')].find((r) => !r.classList.contains('codegen-panel__result--pass') && !r.classList.contains('codegen-panel__result--error'));
  return {
    timeout: (p.querySelector('.codegen-panel__timeout input') || {}).value ?? null,
    errors: [...p.querySelectorAll('.codegen-panel__error')].map((e) => e.textContent),
    first: (() => { const c = p.querySelector('.codegen-panel__code'); return c ? (c.innerText || '').split('\n').map((l) => l.replace(/^\s*\d+\s*/, '')).find((l) => l.trim() !== '') || null : null; })(),
    select: select ? { disabled: select.disabled, value: select.value, options: [...select.options].map((o) => o.textContent) } : null,
    check: chk ? { disabled: chk.disabled, text: chk.textContent.trim() } : null,
    ran: plain ? (plain.querySelector('.codegen-panel__label') || {}).textContent || null : null,
    pass: pass ? pass.textContent.trim() : null,
    error: bad ? bad.textContent.trim().slice(0, 300) : null,
  };
})()`;

/** File → «Import Project» on the dashboard, a real hover and click, and the file given to the chooser it opens. */
async function importFile(page: Page, file: string): Promise<{ id: string; name: string } | null> {
    const before = await page.evaluate(PROJECTS) as Array<{ id: string; name: string }>;
    const menu = page.locator('.nav-hamburger', { has: page.locator(':scope > .menu-title', { hasText: /^File$/ }) });
    await menu.hover();
    const entry = menu.locator('li', { has: page.locator(':scope > label span span', { hasText: /^Import Project$/ }) });
    const chooser = page.waitForEvent('filechooser', { timeout: 15000 });
    await entry.click();
    await (await chooser).setFiles(file);
    const added = await poll<{ id: string; name: string }>(page, String.raw`(() => {
      const ids = new Set(${JSON.stringify(before.map(p => p.id))});
      return ${PROJECTS}.find((p) => !ids.has(p.id)) || null;
    })()`, 30000);
    // The menu stays open while it holds the focus: blurred, and the pointer moved off it.
    await page.evaluate(`(() => { const a = document.activeElement; if (a && a instanceof HTMLElement) a.blur(); })()`);
    await page.mouse.move(800, 900);
    await wait(page, 500);
    return added;
}

async function dashboard(page: Page) {
    await page.goto(`${URL}/#/allProjects`, { waitUntil: 'domcontentloaded', timeout: 300000 });
    await poll(page, `!!(window.windoww && window.windoww.store && window.LPointerTargetable)`, 120000);
    await poll(page, `!!document.querySelector('.nav-hamburger .menu-title')`, 60000);
    await wait(page, 1500);
}

async function clickAndWait(page: Page, panel: string, label: 'Run' | 'Check'): Promise<any> {
    await page.evaluate(String.raw`(() => { const p = ${panel}; [...p.querySelectorAll('.codegen-panel__result')].forEach((r) => r.setAttribute('data-probe-stale', '1')); })()`);
    const button = page.locator(`[role="tabpanel"] .codegen-panel__run button`, { hasText: new RegExp(`^${label}$`) }).first();
    // A disabled button is not clicked: the state is read as it is, and the check that follows reports it.
    if (await button.isDisabled()) return page.evaluate(STATE(panel));
    await button.click();
    const busy = label === 'Run' ? 'Running' : 'Checking';
    const done = await poll<boolean>(page, String.raw`(() => {
      const p = ${panel};
      const r = p.querySelector('.codegen-panel__result:not([data-probe-stale])');
      const b = [...p.querySelectorAll('.codegen-panel__run button')].find((x) => /^(${label}|${busy})$/.test(x.textContent.trim()));
      return r && b && b.textContent.trim() === ${JSON.stringify(label)} ? true : null;
    })()`, 90000);
    return done ? page.evaluate(STATE(panel)) : null;
}

/** Opens the project and its model, the setting on, Generate, Run, Check: the pass line, or null. */
async function generateRunCheck(page: Page, name: string, which: string, pid: string, ex: Example, setting: boolean): Promise<Record<string, any>> {
    const r: Record<string, any> = {};
    await page.goto(`${URL}/?open=${encodeURIComponent(pid)}#/project?id=${pid}`, { waitUntil: 'domcontentloaded', timeout: 300000 });
    const loaded = await poll<{ mm: string; m1: string }>(page, LOADED(ex.lookup.MM.name, ex.lookup.M.name), 120000);
    check(`${name} ${which}: the project opens with the model ${ex.lookup.M.name}`, !!loaded, JSON.stringify(loaded));
    if (!loaded) return r;
    await wait(page, 3000);
    await page.evaluate(String.raw`(async () => { const dm = await import('/src/components/abstract/DockManager.tsx'); await dm.default.open2(window.LPointerTargetable.fromPointer(${JSON.stringify(loaded.m1)})); })()`);
    const pane = PANE(loaded.m1);
    await poll(page, `(() => { const p = ${pane}; return !!p && p.querySelectorAll('.react-flow__node').length > 0; })()`, 60000);
    await wait(page, 2000);

    if (setting) {
        check(`${name} ${which}: no Code pill before the setting`, await page.evaluate(`document.querySelectorAll('.codegen-pill').length`) === 0, '');
        await page.keyboard.press('Control+,');
        await poll(page, `!!document.querySelector('.unified-settings-modal.visible')`, 10000);
        await page.evaluate(CLICK(`[...document.querySelectorAll('.settings-nav-item')].find((b) => b.textContent.trim() === 'Advanced')`));
        await wait(page, 600);
        await page.evaluate(CLICK(`[...document.querySelectorAll('.settings-checkbox')].find((l) => (l.textContent || '').includes('Code generation')).querySelector('input')`));
        await wait(page, 300);
        check(`${name} ${which}: Settings → Advanced → Code generation turns the setting on`, await page.evaluate(`localStorage.getItem('jjodel.experimental.codegen')`) === 'true', '');
        await page.evaluate(CLICK(`document.querySelector('.unified-settings-close')`));
        await wait(page, 600);
    }

    check(`${name} ${which}: the Code pill is on the model's editor`, !!(await poll(page, `!!(${pane} && ${pane}.querySelector('.codegen-pill button'))`, 30000)), '');
    await page.evaluate(CLICK(`${pane}.querySelector('.codegen-pill button')`));
    const panel = `${pane}.querySelector('.codegen-panel')`;
    check(`${name} ${which}: the pill opens the panel`, !!(await poll(page, `!!(${panel})`, 60000)), '');
    await page.evaluate(CLICK(`[...${panel}.querySelectorAll('.codegen-panel__tab')].find((b) => b.textContent.trim() === 'Output')`));
    await poll(page, `!!(${panel}.querySelector('.codegen-panel__code'))`, 30000);
    await page.evaluate(CLICK(`[...${panel}.querySelectorAll('.codegen-panel__button')].find((b) => b.textContent.trim() === 'Generate')`));
    await wait(page, 800);

    const generated = await page.evaluate(STATE(panel)) as any;
    r.generated = generated;
    check(`${name} ${which}: Generate, no error`, !!generated && generated.errors.length === 0, JSON.stringify(generated?.errors ?? null));
    check(`${name} ${which}: the program is the one of its own templates («${HEADER[name]}»)`, (generated?.first ?? '').startsWith(HEADER[name]), JSON.stringify(generated?.first ?? null));
    check(`${name} ${which}: the select lists the stored scenario alone, Check enabled`,
        JSON.stringify(generated?.select?.options) === JSON.stringify([ex.scenario.name]) && generated?.check?.disabled === false, JSON.stringify(generated?.select ?? null));

    const ran = await clickAndWait(page, panel, 'Run');
    r.run = ran;
    note(`${name} ${which}: Run at timeout ${ran?.timeout}`, { ran: ran?.ran, error: ran?.error });
    check(`${name} ${which}: Run at the default timeout, main() returns with no runtime error`, !!ran && !ran.error && /^main\(\) returned, \d+ ms$/.test(ran.ran ?? ''), JSON.stringify(ran?.error ?? ran?.ran ?? null));

    const checked = await clickAndWait(page, panel, 'Check');
    r.check = checked;
    const expected = `Agrees with the simulator on ${STEPS[name]} steps · ${ex.scenario.name}`;
    check(`${name} ${which}: Check on the stored scenario: «${expected}»`, checked?.pass === expected, JSON.stringify(checked?.pass ?? checked?.error ?? null));
    r.panelBox = await page.evaluate(BOX(panel));
    r.panel = panel;
    return r;
}

/** The line of the README's «Trying the mutation», as the student copies it. */
function readmeLine(name: string): string | null {
    const readme = readFileSync(new globalThis.URL(`../../src/codegen/examples/${name}/README.md`, import.meta.url), 'utf8');
    const section = readme.slice(readme.indexOf('### Trying the mutation'));
    return /^\s*(for \(const t of TRANSITIONS\).*)$/m.exec(section)?.[1] ?? null;
}

/** Writes `body` as the `main` template in the Templates tab, saves, and generates in Output. */
async function saveMain(page: Page, panel: string, edit: (body: string) => string | null): Promise<string | null> {
    const tab = (label: string) => page.evaluate(CLICK(`[...${panel}.querySelectorAll('.codegen-panel__tab')].find((b) => b.textContent.trim() === '${label}')`));
    await tab('Templates');
    await poll(page, `!!(${panel}.querySelector('.codegen-panel__item'))`, 10000);
    await page.evaluate(CLICK(`[...${panel}.querySelectorAll('.codegen-panel__item')].find((b) => b.querySelector('.codegen-panel__item-name').textContent === 'main')`));
    await wait(page, 300);
    const textarea = page.locator('.codegen-panel__editor textarea');
    const before = await textarea.inputValue();
    const after = edit(before);
    if (after === null) return null;
    await textarea.fill(after);
    await page.locator('.codegen-panel__editor .codegen-panel__button--primary').click();
    await wait(page, 500);
    await tab('Output');
    await poll(page, `!!(${panel}.querySelector('.codegen-panel__code'))`, 30000);
    await page.evaluate(CLICK(`[...${panel}.querySelectorAll('.codegen-panel__button')].find((b) => b.textContent.trim() === 'Generate')`));
    await wait(page, 800);
    return before;
}

/** The README's mutation, applied as it says: Check diverges at the fixture's step and transition; removed, it agrees. */
async function readmeMutation(page: Page, name: string, panel: string, ex: Example) {
    const line = readmeLine(name);
    check(`${name}: the README gives the mutation's line`, !!line, String(line));
    if (!line) return;
    const end = '${engine()}"';
    const original = await saveMain(page, panel, body => (body.trimEnd().endsWith(end) ? `${body.trimEnd().slice(0, -1)}\n${line}\n"` : null));
    check(`${name}: the main template ends with ${end}, as the README says`, original !== null, '');
    if (original === null) return;
    const generated = await page.evaluate(STATE(panel)) as any;
    check(`${name}: with the README's line, Generate has no error`, !!generated && generated.errors.length === 0, JSON.stringify(generated?.errors ?? null));
    const bad = await clickAndWait(page, panel, 'Check');
    const m = ex.mutation;
    const [tr, from, to] = [m.transition, m.from, m.to].map(id => ex.lookup[id].name as string);
    check(`${name}: Check reports «Diverges at step ${m.step} · ${tr}», with place ${from} and place ${to}`,
        !!bad?.error && bad.error.startsWith(`Diverges at step ${m.step} · ${tr}`) && bad.error.includes(`place ${from}:`) && bad.error.includes(`place ${to}:`),
        JSON.stringify(bad?.error ?? bad?.pass ?? null));
    await saveMain(page, panel, () => original);
    const back = await clickAndWait(page, panel, 'Check');
    check(`${name}: the line removed, Check agrees again`, back?.pass === `Agrees with the simulator on ${STEPS[name]} steps · ${ex.scenario.name}`, JSON.stringify(back?.pass ?? back?.error ?? null));
}

